/**
 * Bundles Moku's 2.5D renderer (src/lib/moku/renderer.js, with three.js) into
 * static/moku/moku-3d.js.
 *
 * It lives outside the app's build on purpose: the service worker precaches
 * every hashed chunk of the build, and three.js would add ~580 KB to that for
 * every visitor, while only those who open the chat need it. static/moku/ is
 * not precached. Also writes src/lib/generated/moku-3d.ts with a content-hashed
 * URL. Runs before every build (npm "prebuild"); the output is committed so a
 * dev server works without running it.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = join(root, 'static/moku/moku-3d.js');

await build({
  entryPoints: [join(root, 'src/lib/moku/renderer.js')],
  outfile,
  bundle: true,
  minify: true,
  format: 'esm',
  target: 'es2020',
  legalComments: 'eof',
  logLevel: 'warning',
});

const hash = createHash('sha256').update(readFileSync(outfile)).digest('hex').slice(0, 10);
writeFileSync(
  join(root, 'src/lib/generated/moku-3d.ts'),
  `// Generated by scripts/build-moku.mjs. Do not edit.\nexport const MOKU_3D_URL = '/moku/moku-3d.js?v=${hash}';\n`,
);
console.log(`moku renderer: ${(readFileSync(outfile).length / 1024).toFixed(0)} KB, v=${hash}`);
